import assert from "node:assert/strict";
import { describe, it } from "node:test";
import { cpSync, mkdirSync, readFileSync, rmSync, symlinkSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { parse, stringify } from "yaml";
import { cli, REPO_ROOT, tmp } from "./helpers.js";
import { PORTAL_ONLY_KEYS, renderGeneratedFiles } from "../src/index.js";
import { stableJson } from "../src/provisioning/generate.js";

// The pipelines' generated inputs (ADR-0074): pipelines/inputs/provisioning.json and
// pipelines/inputs/platform-<env>.json, which the generated pipelines' merge triggers name instead of
// instance.yaml, so a merge that changes nothing a pipeline reads doesn't start it.

type Doc = Record<string, any>; // eslint-disable-line @typescript-eslint/no-explicit-any

const EXAMPLE = join(REPO_ROOT, "config", "examples", "instance.example.yaml");
const EXAMPLE_APP = join(REPO_ROOT, "config", "examples", "apps", "hotel-inventory", "app.yaml");

/** A platform-config laid out like an instance's, from the example instance and app (or another instance.yaml). */
function exampleConfig(instanceYaml = readFileSync(EXAMPLE, "utf8")): string {
  const dir = join(tmp("pc-inputs-"), "platform-config");
  mkdirSync(join(dir, "apps", "hotel-inventory"), { recursive: true });
  writeFileSync(join(dir, "instance.yaml"), instanceYaml);
  cpSync(EXAMPLE_APP, join(dir, "apps", "hotel-inventory", "app.yaml"));
  return dir;
}

const exampleDoc = (): Doc => parse(readFileSync(EXAMPLE, "utf8")) as Doc;
const json = (dir: string, rel: string): Doc => JSON.parse(readFileSync(join(dir, rel), "utf8")) as Doc;
const generated = (dir: string): void => {
  const r = cli(["generate", "--config-dir", dir]);
  assert.equal(r.code, 0, r.stdout + r.stderr);
};

/** Which generated files change when instance.yaml is edited by `edit` (the merge triggers' view of it). */
function changedBy(edit: (doc: Doc) => void): string[] {
  const doc = exampleDoc();
  const before = renderGeneratedFiles(stringify(doc), [readFileSync(EXAMPLE_APP, "utf8")], { today: "2026-11-21" });
  edit(doc);
  const after = renderGeneratedFiles(stringify(doc), [readFileSync(EXAMPLE_APP, "utf8")], { today: "2026-11-21" });
  return [...after.keys()].filter((k) => before.get(k) !== after.get(k));
}

describe("platform generate: the pipelines' inputs (ADR-0074)", () => {
  it("writes pipelines/inputs/provisioning.json and one platform-<env>.json per environment, deterministic and sorted", () => {
    const dir = exampleConfig();
    const r = cli(["generate", "--config-dir", dir]);
    assert.equal(r.code, 0, r.stderr);
    assert.match(r.stdout, /^created {3}pipelines\/platform-prod\.yml\ncreated {3}pipelines\/inputs\/provisioning\.json\ncreated {3}pipelines\/inputs\/platform-nonprod\.json\ncreated {3}pipelines\/inputs\/platform-prod\.json\n/m);
    for (const f of ["provisioning", "platform-nonprod", "platform-prod"]) {
      const text = readFileSync(join(dir, "pipelines", "inputs", `${f}.json`), "utf8");
      assert.equal(text, stableJson(JSON.parse(text)), `${f}.json is in the stable form`);
      assert.match(text, /^\{\n {2}"\$comment": "GENERATED by `platform generate` from instance\.yaml: do not edit\./);
    }
    // Another order of the same keys in instance.yaml: the same files.
    const doc = exampleDoc();
    const reordered = Object.fromEntries(Object.entries(doc).reverse());
    const other = exampleConfig(stringify(reordered));
    generated(other);
    for (const f of ["provisioning", "platform-nonprod", "platform-prod"]) {
      assert.equal(readFileSync(join(other, "pipelines", "inputs", `${f}.json`), "utf8"), readFileSync(join(dir, "pipelines", "inputs", `${f}.json`), "utf8"), f);
    }
    assert.equal(cli(["generate", "--config-dir", dir, "--check"]).code, 0);
  });

  it("stableJson sorts the keys at every level, keeps array order, drops undefined and ends with a newline", () => {
    assert.equal(stableJson({ b: 1, a: { d: [3, 1], c: undefined, "10": true }, $c: null }), '{\n  "$c": null,\n  "a": {\n    "10": true,\n    "d": [\n      3,\n      1\n    ]\n  },\n  "b": 1\n}\n');
    assert.equal(stableJson({ a: [], b: {} }), '{\n  "a": [],\n  "b": {}\n}\n');
  });

  it("provisioning.json: instance.yaml without the keys only the portal reads", () => {
    const dir = exampleConfig();
    generated(dir);
    const doc = exampleDoc();
    const out = json(dir, "pipelines/inputs/provisioning.json");
    assert.deepEqual(out.leftOut, ["setup", "lifecycle", "observability.auditRetentionDays", "branding.logoUrl", "branding.primaryColor", "productName", "portal.cliClientId"]);
    assert.deepEqual(out.leftOut, [...PORTAL_ONLY_KEYS]);
    doc.branding.logoUrl = "https://brand.contoso.com/logo.svg";
    const withLogo = exampleConfig(stringify(doc));
    generated(withLogo);
    assert.equal(readFileSync(join(withLogo, "pipelines/inputs/provisioning.json"), "utf8"), readFileSync(join(dir, "pipelines/inputs/provisioning.json"), "utf8"));
    const expected = structuredClone(doc);
    delete expected.setup;
    delete expected.lifecycle;
    delete expected.observability.auditRetentionDays;
    delete expected.branding; // primaryColor and logoUrl only: the block goes with them
    delete expected.productName;
    delete expected.portal.cliClientId;
    assert.ok(doc.setup && doc.lifecycle && doc.observability.auditRetentionDays !== undefined && doc.branding.primaryColor && doc.productName && doc.portal.cliClientId, "the example sets them all");
    assert.deepEqual(out.instance, expected);
    // A parent left empty goes too: adding the key alone doesn't change the file.
    const bare = exampleDoc();
    bare.observability = { auditRetentionDays: 400 };
    const withBlock = exampleConfig(stringify(bare));
    generated(withBlock);
    delete bare.observability;
    const without = exampleConfig(stringify(bare));
    generated(without);
    assert.equal(readFileSync(join(withBlock, "pipelines/inputs/provisioning.json"), "utf8"), readFileSync(join(without, "pipelines/inputs/provisioning.json"), "utf8"));
  });

  it("platform-<env>.json: the resolved inputs of environment.bicepparam and, in the portal host, portal.bicepparam, without core's digests and Azure's facts", () => {
    const dir = exampleConfig();
    generated(dir);
    const prod = json(dir, "pipelines/inputs/platform-prod.json");
    const nonprod = json(dir, "pipelines/inputs/platform-nonprod.json");
    assert.deepEqual(Object.keys(prod), ["$comment", "environment", "portal", "subscriptionId"]);
    assert.equal(nonprod.portal, null, "only the portal host deploys the portal");
    assert.equal(prod.subscriptionId, exampleDoc().environments.find((e: Doc) => e.name === "prod").subscriptionId);
    // `platform environment inputs` without the saf-jobs digest.
    const images = join(REPO_ROOT, "images", "images.json");
    const envOut = join(tmp(), "env.json");
    assert.equal(cli(["environment", "inputs", "--instance", join(dir, "instance.yaml"), "--env", "nonprod", "--images", images, "--pass", "2", "--output", envOut]).code, 0);
    const envInputs = JSON.parse(readFileSync(envOut, "utf8")) as Doc;
    assert.match(envInputs.platformJobsImageDigest, /^sha256:/);
    delete envInputs.platformJobsImageDigest;
    assert.deepEqual(nonprod.environment, envInputs);
    // `platform environment portal-inputs` without the saf-portal digest, the SMTP secret's state and the ranges.
    const portalOut = join(tmp(), "portal.json");
    assert.equal(cli(["environment", "portal-inputs", "--instance", join(dir, "instance.yaml"), "--env", "prod", "--images", images, "--pass", "auto", "--output", portalOut]).code, 0);
    const portalInputs = JSON.parse(readFileSync(portalOut, "utf8")) as Doc;
    assert.match(portalInputs.portalImageDigest, /^sha256:/);
    delete portalInputs.portalImageDigest;
    delete portalInputs.smtpPasswordSecretExists;
    delete portalInputs.frontDoor.backendIpRanges;
    assert.deepEqual(prod.portal, portalInputs);
    assert.equal(prod.portal.portalClientId, exampleDoc().portal.clientId, "pass 2's values");
    const text = readFileSync(join(dir, "pipelines/inputs/platform-prod.json"), "utf8");
    assert.doesNotMatch(text, /sha256:|ImageDigest|backendIpRanges|smtpPasswordSecretExists/);
  });

  it("values that don't resolve are listed, so fixing them changes the file (an instance before its identities exist)", () => {
    const doc = exampleDoc();
    delete doc.identities.entraProvisioningPrincipalId;
    delete doc.portal.clientId;
    const dir = exampleConfig(stringify(doc));
    generated(dir);
    const prod = json(dir, "pipelines/inputs/platform-prod.json");
    assert.equal(prod.environment.unresolved.length, 1);
    assert.match(prod.environment.unresolved[0], /identities\.entraProvisioningPrincipalId is required by the platform pipeline/);
    assert.equal(prod.portal.portalClientId, "", "no client ID yet: the portal waits for it");
  });

  it("a change only the portal reads starts no pipeline; one a pipeline reads changes its inputs", () => {
    assert.deepEqual(
      changedBy((d) => (d.setup = { confirmed: ["S02", "S03", "S04", "S05"] })),
      [],
      "the setup wizard's progress",
    );
    assert.deepEqual(
      changedBy((d) => (d.lifecycle = { ...d.lifecycle, recertificationMonths: 6 })),
      [],
      "the lifecycle rules",
    );
    assert.deepEqual(
      changedBy((d) => (d.observability.auditRetentionDays = 731)),
      [],
      "the audit log's retention",
    );
    assert.deepEqual(
      changedBy((d) => (d.branding = { primaryColor: "#00594F", logoUrl: "https://brand.contoso.com/logo.png" })),
      [],
      "the portal's look",
    );
    // The ManagedBy tag is fixed (ADR-0002, amended 2026-11-22): a new portal name re-tags nothing.
    assert.deepEqual(
      changedBy((d) => (d.productName = "Contoso Apps Portal")),
      [],
      "the portal's name",
    );
    // The app themes a new app's repository is seeded with: provisioning.
    assert.deepEqual(changedBy((d) => (d.branding.defaultAppTheme = "none")), ["pipelines/inputs/provisioning.json"]);
    // The platform team's address: prod landing zones' alert emails and every environment's alert action group.
    assert.deepEqual(
      changedBy((d) => (d.notifications.email.platformTeamAddress = "ops@contoso.com")),
      ["pipelines/inputs/provisioning.json", "pipelines/inputs/platform-nonprod.json", "pipelines/inputs/platform-prod.json"],
    );
    // The log retention: provisioning reads instance.yaml as a whole, the platform pipelines their workspaces.
    assert.deepEqual(changedBy((d) => (d.observability.logRetentionDays = 30)), ["pipelines/inputs/provisioning.json", "pipelines/inputs/platform-nonprod.json", "pipelines/inputs/platform-prod.json"]);
    // The maintenance window: provisioning only, and its schedule.
    assert.deepEqual(changedBy((d) => (d.maintenance = { window: { days: ["sat"], start: "02:00", hours: 4 } })), ["pipelines/provisioning.yml", "pipelines/inputs/provisioning.json"]);
    // The portal's client ID: the portal host's platform pipeline (and provisioning, which reads all of instance.yaml).
    assert.deepEqual(changedBy((d) => (d.portal.clientId = "00000000-0000-0000-0000-00000000e199")), ["pipelines/inputs/provisioning.json", "pipelines/inputs/platform-prod.json"]);
    // A core upgrade: every pipeline file, through its core ref.
    const upgrade = changedBy((d) => (d.coreVersion = "v9.9.9"));
    for (const f of ["apps/hotel-inventory/delivery.yml", "pipelines/provisioning.yml", "pipelines/validation.yml", "pipelines/platform-nonprod.yml", "pipelines/platform-prod.yml"]) assert.ok(upgrade.includes(f), f);
  });

  it("--check of a platform-config without the inputs (an instance on an older core) says what to run", () => {
    const dir = exampleConfig();
    generated(dir);
    rmSync(join(dir, "pipelines", "inputs"), { recursive: true });
    const r = cli(["generate", "--config-dir", dir, "--check"]);
    assert.equal(r.code, 1);
    assert.match(r.stdout, /^DRIFT +pipelines\/inputs\/provisioning\.json \(missing\)$/m);
    assert.match(r.stdout, /^The pipelines' inputs \(pipelines\/inputs\/provisioning\.json and pipelines\/inputs\/platform-<env>\.json; ADR-0074\) are missing/m);
    assert.match(r.stdout, /^Fix: in a clone of platform-config, run "platform generate --config-dir \." with the CLI of coreVersion and commit every file it writes in a pull request \(core: docs\/runbooks\/upgrade-instance-core\.md, step 3\)\.$/m);
    // An edited inputs file is ordinary drift.
    generated(dir);
    writeFileSync(join(dir, "pipelines", "inputs", "platform-nonprod.json"), "{}\n");
    const edited = cli(["generate", "--config-dir", dir, "--check"]);
    assert.equal(edited.code, 1);
    assert.match(edited.stdout, /^DRIFT +pipelines\/inputs\/platform-nonprod\.json$/m);
    assert.match(edited.stdout, /^Fix: run "platform generate --config-dir \." with the CLI of coreVersion and commit every file it writes\.$/m);
  });

  it("refuses a symbolic link as pipelines/inputs", () => {
    const dir = exampleConfig();
    generated(dir);
    rmSync(join(dir, "pipelines", "inputs"), { recursive: true });
    const elsewhere = join(tmp(), "elsewhere");
    mkdirSync(elsewhere);
    symlinkSync(elsewhere, join(dir, "pipelines", "inputs"));
    const r = cli(["generate", "--config-dir", dir]);
    assert.equal(r.code, 1);
    assert.match(r.stderr, /pipelines\/inputs is not a directory/);
  });
});

describe("library renderGeneratedFiles (ADR-0074)", () => {
  it("returns exactly what platform generate writes, in its order", () => {
    const dir = exampleConfig();
    const r = cli(["generate", "--config-dir", dir]);
    assert.equal(r.code, 0, r.stderr);
    const files = renderGeneratedFiles(readFileSync(join(dir, "instance.yaml"), "utf8"), [readFileSync(join(dir, "apps", "hotel-inventory", "app.yaml"), "utf8")]);
    const listed = r.stdout
      .split("\n")
      .filter((l) => l.startsWith("created"))
      .map((l) => l.replace(/^created +/, ""));
    assert.deepEqual([...files.keys()], listed);
    for (const [path, text] of files) assert.equal(text, readFileSync(join(dir, path), "utf8"), path);
  });

  it("without apps: the pipelines, their inputs and the AI guide", () => {
    const files = renderGeneratedFiles(readFileSync(EXAMPLE, "utf8"));
    assert.ok(!["apps/"].some((p) => [...files.keys()].some((k) => k.startsWith(p))));
    assert.ok(files.has("pipelines/inputs/provisioning.json") && files.has("pipelines/inputs/platform-prod.json") && files.has("AGENTS.md"));
  });

  it("an invalid instance or app definition is a PlatformConfigError with its problems", () => {
    assert.throws(() => renderGeneratedFiles("coreVersion: [\n"), (e: Error & { problems?: unknown[] }) => e.name === "PlatformConfigError" && (e.problems?.length ?? 0) > 0);
    const app = parse(readFileSync(EXAMPLE_APP, "utf8")) as Doc;
    app.environments.qa = app.environments.nonprod;
    assert.throws(
      () => renderGeneratedFiles(readFileSync(EXAMPLE, "utf8"), [stringify(app)]),
      (e: Error & { problems?: { message: string }[] }) => e.name === "PlatformConfigError" && e.problems!.some((p) => /^apps\/hotel-inventory\/app\.yaml: .*qa/.test(p.message)),
    );
  });
});

